import { readFileSync } from 'node:fs'
import type { Entry } from './check-versions.ts'

// Weekly version and support report (#512). Prints the body of the single `Version check` Issue.
export type Release = { name: string, eolFrom: string | null, ltsFrom?: string | null, latest?: { name: string } | null }
export type Facts = { latest?: string, support?: string, notes: string[], failures: string[] }
type Fetch = (url: string) => Promise<{ status: number, json: () => Promise<unknown> }>

export const marker = '<!-- version-check: generated by .github/workflows/version-check.yml -->'

function cycleOf(entry: Entry, releases: Release[]): Release | undefined {
  if (entry.cycle) return releases.find(release => release.name === entry.cycle)
  return releases.filter(release => entry.version === release.name || entry.version.startsWith(`${release.name}.`))
    .sort((a, b) => b.name.length - a.name.length)[0]
}

export function newer(latest: string, pinned: string): boolean {
  const parts = (version: string) => version.split('.').map(Number)
  const [a, b] = [parts(latest), parts(pinned)]
  if ([...a, ...b].some(Number.isNaN)) return latest !== pinned
  for (let at = 0; at < Math.max(a.length, b.length); at++) {
    if ((a[at] ?? 0) !== (b[at] ?? 0)) return (a[at] ?? 0) > (b[at] ?? 0)
  }
  return false
}

// Highest release line by version, never by the API's array order.
export function newestLine(releases: Release[], lts: boolean, today: string): Release | undefined {
  return releases
    .filter(release => release.latest && (!lts || (release.ltsFrom != null && release.ltsFrom <= today)))
    .reduce<Release | undefined>((best, release) => !best || newer(release.latest!.name, best.latest!.name) ? release : best, undefined)
}

export async function gather(entries: Entry[], fetch: Fetch, today: string): Promise<Map<string, Facts>> {
  const products = new Map<string, Promise<Release[] | 'missing'>>()
  const releases = (product: string) => {
    if (!products.has(product)) products.set(product, (async () => {
      const response = await fetch(`https://endoflife.date/api/v1/products/${product}/`)
      if (response.status === 404) return 'missing' as const
      if (response.status !== 200) throw new Error(`endoflife.date ${product}: HTTP ${response.status}`)
      return ((await response.json()) as { result: { releases: Release[] } }).result.releases
    })())
    return products.get(product)!
  }
  const facts = new Map<string, Facts>()
  for (const entry of entries) {
    const fact: Facts = { notes: [], failures: [] }
    facts.set(entry.component, fact)
    if (entry.endoflife) {
      try {
        const found = await releases(entry.endoflife)
        const cycle = found === 'missing' ? undefined : cycleOf(entry, found)
        if (found === 'missing') fact.notes.push(`${entry.endoflife} is not on endoflife.date`)
        else if (!cycle) fact.notes.push(`no ${entry.endoflife} cycle on endoflife.date matches ${entry.version}`)
        else fact.support = cycle.eolFrom ?? 'no end announced'
      } catch (error) { fact.failures.push(String(error)) }
    }
    if (!entry.latest) continue
    try {
      if ('github' in entry.latest) {
        const response = await fetch(`https://api.github.com/repos/${entry.latest.github}/releases/latest`)
        if (response.status !== 200) throw new Error(`GitHub ${entry.latest.github}: HTTP ${response.status}`)
        fact.latest = ((await response.json()) as { tag_name: string }).tag_name.replace(/^v/, '')
      } else {
        const lts = entry.latest.lts
        const found = await releases(entry.latest.endoflife)
        if (found === 'missing') throw new Error(`${entry.latest.endoflife} is not on endoflife.date`)
        const line = newestLine(found, !!lts, today)
        if (!line?.latest) throw new Error(`endoflife.date ${entry.latest.endoflife}: no ${lts ? 'LTS ' : ''}release with a latest version`)
        fact.latest = line.latest.name
      }
    } catch (error) { fact.failures.push(String(error)) }
  }
  return facts
}

// Clamps to the target month's last day (Aug 31 + 6 months = Feb 28/29), never rolling into the next month.
export function addMonths(date: string, months: number): string {
  const [year, month, day] = date.split('-').map(Number)
  const target = new Date(Date.UTC(year, month - 1 + months, 1))
  const last = new Date(Date.UTC(target.getUTCFullYear(), target.getUTCMonth() + 1, 0)).getUTCDate()
  target.setUTCDate(Math.min(day, last))
  return target.toISOString().slice(0, 10)
}

export function report(entries: Entry[], facts: Map<string, Facts>, today: string): string {
  const soon = addMonths(today, 6)
  const rows = { newer: [] as string[], soon: [] as string[], past: [] as string[], failures: [] as string[], notes: [] as string[] }
  for (const entry of entries) {
    const fact = facts.get(entry.component) ?? { notes: [], failures: ['no result gathered'] }
    const where = `\`${entry.file}\``
    if (fact.latest && newer(fact.latest, entry.version)) {
      const major = fact.latest.split('.')[0] !== entry.version.split('.')[0] ? ', new major: one Issue, maintainer decides' : ''
      rows.newer.push(`- ${entry.component}: ${entry.version} -> ${fact.latest} (${where}, ${entry.class}${major})`)
    }
    const end = /^\d{4}-\d{2}-\d{2}$/.test(fact.support ?? '') ? fact.support! : /^\d{4}-\d{2}-\d{2}$/.test(entry.support) ? entry.support : undefined
    const source = fact.support === end && end ? 'endoflife.date' : 'versions.json'
    if (end && end < today) rows.past.push(`- ${entry.component} ${entry.version}: support ended ${end} (${source})`)
    else if (end && end <= soon) rows.soon.push(`- ${entry.component} ${entry.version}: support ends ${end} (${source})`)
    if (fact.support && /^\d{4}-\d{2}-\d{2}$/.test(fact.support) && /^\d{4}-\d{2}-\d{2}$/.test(entry.support) && fact.support !== entry.support) {
      rows.notes.push(`- ${entry.component}: versions.json says ${entry.support}, endoflife.date says ${fact.support}`)
    }
    for (const failure of fact.failures) rows.failures.push(`- ${entry.component}: ${failure}`)
    for (const note of fact.notes) rows.notes.push(`- ${entry.component}: ${note}`)
  }
  const section = (title: string, lines: string[]) => [`## ${title}`, lines.length ? lines.join('\n') : '- none', '']
  return [marker, `Checked ${today} against \`versions.json\` (${entries.length} entries). Rules: \`docs/workflow.md\` section 8.`, '',
    ...section('Newer versions available', rows.newer),
    ...section('Support ends within 6 months', rows.soon),
    ...section('Past support end', rows.past),
    ...section('Upstream failures (not checked this run)', rows.failures),
    ...section('Notes', rows.notes)].join('\n')
}

if (import.meta.main) {
  const entries: Entry[] = JSON.parse(readFileSync(new URL('../versions.json', import.meta.url), 'utf8')).entries
  const token = process.env.GITHUB_TOKEN
  const fetchJson: Fetch = url => fetch(url, { headers: url.startsWith('https://api.github.com/') && token
    ? { authorization: `Bearer ${token}`, accept: 'application/vnd.github+json' } : {} })
  const today = new Date().toISOString().slice(0, 10)
  process.stdout.write(report(entries, await gather(entries, fetchJson, today), today))
}
