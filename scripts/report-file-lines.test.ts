import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { test } from 'node:test'
import { GUIDANCE, isGenerated, kindOf, lineCount, markdown, overGuidance } from './report-file-lines.ts'

const lines = (n: number) => 'x\n'.repeat(n)

test('test files are recognised by directory or name; everything else is product', () => {
  for (const path of ['server/tests/schema.rs', 'server/src/auth/cleanup/tests.rs', 'server/src/auth/admission_tests.rs',
    'server/src/auth/invites/tests/management.rs', 'server/src/auth/security/test_support.rs', 'web/src/sync.test.ts',
    'web/e2e/smoke.spec.ts', 'web/src/svelte-dom-test-helpers.ts', 'client-core/tests/differential.rs'])
    assert.equal(kindOf(path), 'test', path)
  for (const path of ['server/src/messages/log.rs', 'web/src/Workspace.svelte', 'load/slice5/fixture.ts',
    'server/src/contest.rs', 'web/src/latest.ts', 'server/src/attestation.rs'])
    assert.equal(kindOf(path), 'product', path)
})

test('the guidance is exclusive: exactly at the count is not over it', () => {
  const rows = overGuidance([
    { path: 'a.rs', text: lines(GUIDANCE.product) },
    { path: 'b.rs', text: lines(GUIDANCE.product + 1) },
    { path: 'c.test.ts', text: lines(GUIDANCE.test) },
    { path: 'd.test.ts', text: lines(GUIDANCE.test + 1) },
    { path: 'e.svelte', text: lines(GUIDANCE.test + 5) },
  ], new Set(['b.rs']))
  assert.deepEqual(rows, [
    { path: 'e.svelte', kind: 'product', lines: 1_005, changed: false },
    { path: 'd.test.ts', kind: 'test', lines: 1_001, changed: false },
    { path: 'b.rs', kind: 'product', lines: 601, changed: true },
  ])
})

test('generated files and other extensions are excluded', () => {
  const big = lines(2_000)
  assert.deepEqual(overGuidance([
    { path: 'web/src/api-schema.d.ts', text: `/**\n * This file was auto-generated by openapi-typescript.\n */\n${big}` },
    { path: 'x.rs', text: `// @generated\n${big}` },
    { path: 'docs/spec.md', text: big },
    { path: 'web/package-lock.json', text: big },
  ], new Set()), [])
  assert.equal(isGenerated(`${lines(5)}// Do not edit\n`), false, 'only the first five lines count')
})

test('line counts match wc -l, with or without a trailing newline', () => {
  assert.equal(lineCount(''), 0)
  assert.equal(lineCount('a'), 1)
  assert.equal(lineCount('a\n'), 1)
  assert.equal(lineCount('a\nb'), 2)
  assert.equal(lineCount('a\n\n'), 2)
})

test('the report lists rows, marks changed files only with a base, and says when nothing is over', () => {
  const rows = [{ path: 'b.rs', kind: 'product' as const, lines: 601, changed: true }]
  const withBase = markdown(rows, true)
  assert.match(withBase, /1 files over the guidance\. 1 changed in this PR/)
  assert.match(withBase, /\| `b\.rs` \| product \| 601 \| 600 \| yes \|/)
  assert.doesNotMatch(markdown(rows, false), /Changed/)
  assert.match(markdown([], true), /No file is over the guidance\./)
})

test('the script reports and exits 0 on this repository', () => {
  const run = spawnSync(process.execPath, ['scripts/report-file-lines.ts'], { encoding: 'utf8', env: { ...process.env, GITHUB_STEP_SUMMARY: '' } })
  assert.equal(run.status, 0, run.stderr)
  assert.match(run.stdout, /^## Files over the line-count guidance \(report only\)/)
})
